// Purpose: regenerate packages/petta/src/builtin-signatures.ts from a PeTTa checkout's
// src/typecheck/builtin_registry.pl: one builtin_signature(Name, Arity, Det, ArgTypes, OutType) fact per
// builtin_spec whose typing column is a signature, the single source of builtin types PeTTa seeds its
// declaration store from (decl_store.pl seed_builtin_types/0).
// am[implements a-pe-types-runtime]
//
// Usage: node scripts/gen-petta-signatures.mjs <PeTTa checkout>   (run after `pnpm --filter @mettascript/petta build`)

import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { readClauses, writeTerm, deref } = await import(join(root, "packages/petta/dist/index.js"));
const petta = resolve(process.argv[2] ?? join(root, "ai-tmp/PeTTa"));
const text = readFileSync(join(petta, "src/typecheck/builtin_registry.pl"), "utf8");
const facts = [];
const cards = [];
for (const c of readClauses(text)) {
  if (c.name !== "builtin_spec" || c.args.length !== 6) continue;
  const [key, , typing, , card] = c.args.map(deref);
  if (deref(key.args[1]) !== "variadic") cards.push(`builtin_cardinality(${writeTerm(key.args[0], { quoted: true })}, ${writeTerm(key.args[1])}, ${writeTerm(card.args[0], { quoted: true })}).`);
  const sig = deref(typing.args?.[0]);
  if (typing.name !== "typing" || sig?.name !== "signature") continue;
  const [det, argTypes, outType] = sig.args.map(deref);
  facts.push(`builtin_signature(${writeTerm(key.args[0], { quoted: true })}, ${writeTerm(key.args[1])}, ${writeTerm(det, { quoted: true })}, ${writeTerm(argTypes, { quoted: true })}, ${writeTerm(outType, { quoted: true })}).`);
}
const commit = (() => {
  try {
    return readFileSync(join(petta, ".git/HEAD"), "utf8").trim();
  } catch {
    return "unknown";
  }
})();
const out = `// SPDX-FileCopyrightText: 2026 MesTTo
//
// SPDX-License-Identifier: MIT

// Purpose: PeTTa's builtin signatures, generated by scripts/gen-petta-signatures.mjs from
// src/typecheck/builtin_registry.pl (checkout HEAD ${commit}); do not edit by hand.
// am[implements a-pe-types-runtime]

export const BUILTIN_SIGNATURES_PL = String.raw\`
${facts.join("\n")}
${cards.join("\n")}
\`;
`;
writeFileSync(join(root, "packages/petta/src/builtin-signatures.ts"), out);
console.log(`${facts.length} signatures, ${cards.length} cardinalities`);
